// Helper to generate random location near Indore
const getRandomLocation = (centerLat: number, centerLon: number, radiusKm: number) => {
  const radiusInDegrees = radiusKm / 111;
  const angle = Math.random() * 2 * Math.PI;
  const randomRadius = Math.random() * radiusInDegrees;
  
  return {
    latitude: centerLat + randomRadius * Math.cos(angle),
    longitude: centerLon + randomRadius * Math.sin(angle),
  };
};

